#!/usr/bin/env python3
"""Turn mpqx 'list' TSVs into committed listings and MPQ_LISTING.md.

usage: python3 -I listing_report.py <_listings dir from run_all.sh> <repo 2_txt dir>

Writes 2_txt/listings/<mpq>.tsv (path, size, compressed size, type) for every archive and
2_txt/MPQ_LISTING.md (per archive: file count, sizes, counts by extension and top folders).
'type' = file extension plus a content check of the first 8 bytes where one is known.
"""
import os
import sys
from collections import Counter, defaultdict

ORDER = ["pd2data", "patch_d2", "pd2maps", "pd2assets", "pd2monchars", "SGD2FreeRes", "D2MultiRes", "d2gl"]
EXTRACTED = {"pd2data", "patch_d2", "pd2maps", "SGD2FreeRes", "D2MultiRes", "d2gl"}


def kind(ext, magic):
    m = bytes.fromhex(magic) if magic else b""
    if m[:4] == b"RIFF":
        k = "wav"
    elif m[:8] == bytes.fromhex("0600000001000000"):
        k = "dc6"
    elif m[:1] == b"\x74" and ext == "dcc":
        k = "dcc"
    elif m[:8] == bytes.fromhex("0700000006000000"):
        k = "dt1"
    elif m[:8] == b"\x89PNG\r\n\x1a\n":
        k = "png"
    elif m[:2] in (b"\xff\xfe", b"\xfe\xff"):
        k = "text-utf16"
    elif m and all(32 <= c < 127 or c in (9, 10, 13) for c in m):
        k = "text"
    else:
        k = "binary"
    if ext in ("dc6", "dcc", "dt1", "wav", "png") and k != ext:
        return "%s (content: %s)" % (ext, k)
    return ext if ext else k


def human(n):
    for u in ("B", "KB", "MB", "GB"):
        if n < 1024 or u == "GB":
            return ("%d %s" % (n, u)) if u == "B" else ("%.1f %s" % (n, u))
        n /= 1024.0


def main(argv):
    src, out = argv[0], argv[1]
    os.makedirs(os.path.join(out, "listings"), exist_ok=True)
    summary = {}
    for line in open(os.path.join(src, "summary.txt")):
        f = dict(p.split("=", 1) for p in line.split() if "=" in p)
        summary[os.path.basename(f["archive"]).rsplit(".", 1)[0]] = f
    L = ["# MPQ listing", "",
         "Generated by `tools/mpq/listing_report.py` from `mpqx list` output. Full per-file listings: "
         "`listings/<mpq>.tsv` (path, size, compressed size, type). Sizes are uncompressed unless marked. "
         "\"unnamed\" = file-table entries no listfile could name (StormLib pseudo name `FileNNNNNNNN.xxx`).", "",
         "| MPQ | archive size | files | named | unnamed | uncompressed | compressed | extracted to workspace |",
         "|---|---:|---:|---:|---:|---:|---:|---|"]
    detail = []
    for m in ORDER:
        p = os.path.join(src, m + ".tsv")
        if not os.path.exists(p):
            continue
        rows = []
        for i, line in enumerate(open(p, encoding="latin-1")):
            c = line.rstrip("\n").split("\t")
            if i == 0:
                continue
            path, size, csize, magic = c[0], int(c[1]), int(c[2]), c[7]
            ext = path.rsplit(".", 1)[1].lower() if "." in path.rsplit("\\", 1)[-1] else ""
            rows.append((path, size, csize, kind(ext, magic)))
        rows.sort(key=lambda r: r[0].lower())
        with open(os.path.join(out, "listings", m + ".tsv"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("path\tsize\tcompressed_size\ttype\n")
            for r in rows:
                fh.write("%s\t%d\t%d\t%s\n" % r)
        s = summary.get(m, {})
        asize = os.path.getsize(s["archive"]) if s.get("archive") and os.path.exists(s["archive"]) else 0
        tot, ctot = sum(r[1] for r in rows), sum(r[2] for r in rows)
        L.append("| %s | %s | %d | %s | %s | %s | %s | %s |" % (m, human(asize), len(rows), s.get("named", "?"),
                 s.get("unnamed", "?"), human(tot), human(ctot), "yes" if m in EXTRACTED else "no (listing only)"))
        byext = defaultdict(lambda: [0, 0])
        for r in rows:
            e = r[3].split(" ")[0] or "(none)"
            byext[e][0] += 1
            byext[e][1] += r[1]
        folders = Counter()
        fsize = Counter()
        for r in rows:
            parts = r[0].lower().split("\\")
            f = "\\".join(parts[:3]) if len(parts) > 3 else "\\".join(parts[:-1]) or "(root)"
            folders[f] += 1
            fsize[f] += r[1]
        detail.append("")
        detail.append("## %s" % m)
        detail.append("")
        detail.append("By type:")
        detail.append("")
        detail.append("| type | files | size |")
        detail.append("|---|---:|---:|")
        for e, (n, sz) in sorted(byext.items(), key=lambda x: -x[1][0]):
            detail.append("| %s | %d | %s |" % (e, n, human(sz)))
        detail.append("")
        detail.append("By folder (first three levels, lower-cased; top 25):")
        detail.append("")
        detail.append("| folder | files | size |")
        detail.append("|---|---:|---:|")
        for f, n in folders.most_common(25):
            detail.append("| `%s` | %d | %s |" % (f, n, human(fsize[f])))
        if len(folders) > 25:
            detail.append("| (%d more folders) | %d | |" % (len(folders) - 25, sum(n for f, n in folders.most_common()[25:])))
        mism = [r for r in rows if "content:" in r[3]]
        if mism:
            detail.append("")
            detail.append("Extension/content mismatches: %d (see the .tsv `type` column)." % len(mism))
    with open(os.path.join(out, "MPQ_LISTING.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L + detail) + "\n")
    print("listings written for %d archives" % len(summary))


if __name__ == "__main__":
    main(sys.argv[1:])
